import { NextRequest, NextResponse } from "next/server";
import { promises as fs } from "fs";
import path from "path";

/**
 * Serves lead attachments from public/uploads.
 *
 * The Next.js standalone server (Next 16) only serves files that existed in
 * public/ at build time, so files written at runtime (customer uploads,
 * admin images) 404 without this handler. Reading from disk directly also
 * keeps working when the folder is a mounted persistent volume.
 */
export const dynamic = "force-dynamic";

const uploadDir = path.join(process.cwd(), "public", "uploads");

const MIME_TYPES: Record<string, string> = {
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".pdf": "application/pdf",
  ".doc": "application/msword",
  ".docx":
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
};

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ filename: string }> }
) {
  const { filename } = await params;

  // Only serve plain names generated by lib/upload.ts (Timestamp-uuid.ext).
  // basename() blocks traversal; the identity check rejects any path parts.
  const safeName = path.basename(filename);
  if (
    safeName !== filename ||
    safeName.includes("..") ||
    safeName.startsWith(".")
  ) {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }

  const filePath = path.join(uploadDir, safeName);

  try {
    const data = await fs.readFile(filePath);
    const ext = path.extname(safeName).toLowerCase();
    return new NextResponse(new Uint8Array(data), {
      status: 200,
      headers: {
        "Content-Type": MIME_TYPES[ext] ?? "application/octet-stream",
        "Cache-Control": "private, max-age=3600",
        "X-Content-Type-Options": "nosniff",
      },
    });
  } catch {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }
}
